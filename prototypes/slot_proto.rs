//! Prototype: slots chosen per field type (filters) and overridden per field
//! (a counter in a patch).
#![allow(dead_code)]

// =========================================================== runtime crate
pub mod muck {
    pub trait Shape: Sized {}

    pub trait FieldOf<S: Shape>: 'static {
        type Type;
        const NAME: &'static str;
        fn get_mut(value: &mut S) -> &mut Self::Type;
    }

    /// A companion kind. It picks the slot of each field, so it can decide
    /// by the field's type or by the field itself.
    pub trait SlotFor<S: Shape, F: FieldOf<S>> {
        type Slot;
    }

    /// The companion of `S` for kind `W`. Generated by the base derive.
    pub trait ShapeWith<W>: Shape {
        type Out;
    }
    pub type With<S, W> = <S as ShapeWith<W>>::Out;

    // Traversals. The visitor trait is keyed by the field and the kind, and
    // gets the slot type through the kind.
    pub trait VisitField<S: Shape, F: FieldOf<S>, W: SlotFor<S, F>> {
        fn visit(&mut self, slot: &W::Slot, value: &F::Type);
    }
    pub trait VisitWithValue<W, V>: ShapeWith<W> {
        fn visit_with_value(with: &Self::Out, value: &Self, visitor: &mut V);
    }

    pub trait ApplyField<S: Shape, F: FieldOf<S>, W: SlotFor<S, F>> {
        fn apply(&mut self, slot: W::Slot, target: &mut F::Type);
    }
    pub trait Apply<W, V>: ShapeWith<W> {
        fn apply(with: Self::Out, target: &mut Self, visitor: &mut V);
    }
}

// =========================================== what the base derive generates
pub mod user {
    use crate::muck::*;

    pub struct Foo {
        pub bar: u32,
        pub zee: String,
        pub nick: Option<String>,
    }

    pub mod foo_field {
        pub struct Bar;
        pub struct Zee;
        pub struct Nick;
    }

    #[derive(Debug, Clone, PartialEq, Default)]
    pub struct FooShape<B, Z, N> {
        pub bar: B,
        pub zee: Z,
        pub nick: N,
    }

    impl Shape for Foo {}

    impl FieldOf<Foo> for foo_field::Bar {
        type Type = u32;
        const NAME: &'static str = "bar";
        fn get_mut(value: &mut Foo) -> &mut u32 {
            &mut value.bar
        }
    }
    impl FieldOf<Foo> for foo_field::Zee {
        type Type = String;
        const NAME: &'static str = "zee";
        fn get_mut(value: &mut Foo) -> &mut String {
            &mut value.zee
        }
    }
    impl FieldOf<Foo> for foo_field::Nick {
        type Type = Option<String>;
        const NAME: &'static str = "nick";
        fn get_mut(value: &mut Foo) -> &mut Option<String> {
            &mut value.nick
        }
    }

    impl<W> ShapeWith<W> for Foo
    where
        W: SlotFor<Foo, foo_field::Bar>
            + SlotFor<Foo, foo_field::Zee>
            + SlotFor<Foo, foo_field::Nick>,
    {
        type Out = FooShape<
            <W as SlotFor<Foo, foo_field::Bar>>::Slot,
            <W as SlotFor<Foo, foo_field::Zee>>::Slot,
            <W as SlotFor<Foo, foo_field::Nick>>::Slot,
        >;
    }

    impl<W, V> VisitWithValue<W, V> for Foo
    where
        W: SlotFor<Foo, foo_field::Bar>
            + SlotFor<Foo, foo_field::Zee>
            + SlotFor<Foo, foo_field::Nick>,
        V: VisitField<Foo, foo_field::Bar, W>
            + VisitField<Foo, foo_field::Zee, W>
            + VisitField<Foo, foo_field::Nick, W>,
    {
        fn visit_with_value(with: &Self::Out, value: &Foo, visitor: &mut V) {
            VisitField::<Foo, foo_field::Bar, W>::visit(visitor, &with.bar, &value.bar);
            VisitField::<Foo, foo_field::Zee, W>::visit(visitor, &with.zee, &value.zee);
            VisitField::<Foo, foo_field::Nick, W>::visit(visitor, &with.nick, &value.nick);
        }
    }

    impl<W, V> Apply<W, V> for Foo
    where
        W: SlotFor<Foo, foo_field::Bar>
            + SlotFor<Foo, foo_field::Zee>
            + SlotFor<Foo, foo_field::Nick>,
        V: ApplyField<Foo, foo_field::Bar, W>
            + ApplyField<Foo, foo_field::Zee, W>
            + ApplyField<Foo, foo_field::Nick, W>,
    {
        fn apply(with: Self::Out, target: &mut Foo, visitor: &mut V) {
            ApplyField::<Foo, foo_field::Bar, W>::apply(visitor, with.bar, &mut target.bar);
            ApplyField::<Foo, foo_field::Zee, W>::apply(visitor, with.zee, &mut target.zee);
            ApplyField::<Foo, foo_field::Nick, W>::apply(visitor, with.nick, &mut target.nick);
        }
    }

    // ---- what a thin `#[derive(Patch)]` adds, for:
    //      #[patch(with = Counter)] bar: u32
    impl crate::patch::PatchField for foo_field::Bar {
        type Slot = crate::patch::Counter;
    }
    impl crate::patch::PatchField for foo_field::Zee {
        type Slot = crate::patch::Replace<String>;
    }
    impl crate::patch::PatchField for foo_field::Nick {
        type Slot = crate::patch::Replace<Option<String>>;
    }
}

// =============================== filter: the slot depends on the field type
pub mod filter {
    use crate::muck::*;

    /// How values of a type are filtered. The filter crate implements this
    /// for std types; a user's type implements it itself.
    pub trait Filterable {
        type Filter;
        fn matches(filter: &Self::Filter, value: &Self) -> bool;
    }

    pub enum Comparison<T> {
        EqualTo(T),
        LessThan(T),
        MoreThan(T),
    }

    impl Filterable for u32 {
        type Filter = Comparison<u32>;
        fn matches(filter: &Comparison<u32>, value: &u32) -> bool {
            match filter {
                Comparison::EqualTo(x) => value == x,
                Comparison::LessThan(x) => value < x,
                Comparison::MoreThan(x) => value > x,
            }
        }
    }

    pub enum StringFilter {
        Equals(String),
        Contains(String),
        Length(Comparison<u32>),
    }

    impl Filterable for String {
        type Filter = StringFilter;
        fn matches(filter: &StringFilter, value: &String) -> bool {
            match filter {
                StringFilter::Equals(x) => value == x,
                StringFilter::Contains(x) => value.contains(x.as_str()),
                StringFilter::Length(length) => {
                    u32::matches(length, &(value.len() as u32))
                },
            }
        }
    }

    pub enum OptionFilter<F> {
        IsSet,
        IsNotSet,
        Value(F),
    }

    impl<T: Filterable> Filterable for Option<T> {
        type Filter = OptionFilter<T::Filter>;
        fn matches(filter: &Self::Filter, value: &Option<T>) -> bool {
            match (filter, value) {
                (OptionFilter::IsSet, value) => value.is_some(),
                (OptionFilter::IsNotSet, value) => value.is_none(),
                (OptionFilter::Value(filter), Some(value)) => T::matches(filter, value),
                (OptionFilter::Value(_), None) => false,
            }
        }
    }

    /// The filter kind: each field gets its type's filter, or none.
    pub struct FilterKind;
    impl<S: Shape, F: FieldOf<S>> SlotFor<S, F> for FilterKind
    where
        F::Type: Filterable,
    {
        type Slot = Option<<F::Type as Filterable>::Filter>;
    }

    pub type Filter<S> = With<S, FilterKind>;

    pub struct Matches(pub bool);
    impl<S: Shape, F: FieldOf<S>> VisitField<S, F, FilterKind> for Matches
    where
        F::Type: Filterable,
    {
        fn visit(&mut self, slot: &Option<<F::Type as Filterable>::Filter>, value: &F::Type) {
            if let Some(filter) = slot {
                self.0 &= <F::Type as Filterable>::matches(filter, value);
            }
        }
    }

    pub fn matches<S: VisitWithValue<FilterKind, Matches>>(
        filter: &Filter<S>,
        value: &S,
    ) -> bool {
        let mut matches = Matches(true);
        S::visit_with_value(filter, value, &mut matches);
        matches.0
    }
}

// ================================ patch: the slot is chosen per field
pub mod patch {
    use crate::muck::*;

    /// What a patch slot does to its field.
    pub trait PatchSlot<T> {
        fn apply(self, target: &mut T);
    }

    /// The default: write a new value, if there is one.
    pub type Replace<T> = Option<T>;
    impl<T> PatchSlot<T> for Option<T> {
        fn apply(self, target: &mut T) {
            if let Some(value) = self {
                *target = value;
            }
        }
    }

    /// Adds to the field, whatever its value. Two counters merge by adding.
    #[derive(Debug, Default, Clone, Copy, PartialEq)]
    pub struct Counter(pub u32);
    impl PatchSlot<u32> for Counter {
        fn apply(self, target: &mut u32) {
            *target += self.0;
        }
    }

    /// The slot of each field in a patch. A thin derive implements this for
    /// every field type, from `#[patch(with = …)]` or the default.
    pub trait PatchField {
        type Slot;
    }

    pub struct PatchKind;
    impl<S: Shape, F: FieldOf<S> + PatchField> SlotFor<S, F> for PatchKind {
        type Slot = F::Slot;
    }

    pub struct Writer;
    impl<S: Shape, F: FieldOf<S> + PatchField> ApplyField<S, F, PatchKind> for Writer
    where
        F::Slot: PatchSlot<F::Type>,
    {
        fn apply(&mut self, slot: F::Slot, target: &mut F::Type) {
            slot.apply(target);
        }
    }

    pub fn apply<S: Apply<PatchKind, Writer>>(changes: With<S, PatchKind>, target: &mut S) {
        S::apply(changes, target, &mut Writer);
    }
}

#[cfg(test)]
mod tests {
    use crate::filter::{self, Comparison, OptionFilter, StringFilter};
    use crate::patch::{self, Counter};
    use crate::user::{Foo, FooShape};

    fn foo() -> Foo {
        Foo {
            bar: 5,
            zee: "hello".into(),
            nick: None,
        }
    }

    #[test]
    fn each_field_gets_the_filter_of_its_type() {
        let filter: filter::Filter<Foo> = FooShape {
            bar: Some(Comparison::MoreThan(3)),
            zee: Some(StringFilter::Length(Comparison::LessThan(10))),
            nick: Some(OptionFilter::IsNotSet),
        };
        assert!(filter::matches(&filter, &foo()));

        let filter: filter::Filter<Foo> = FooShape {
            bar: None,
            zee: Some(StringFilter::Contains("ell".into())),
            nick: Some(OptionFilter::IsSet),
        };
        assert!(!filter::matches(&filter, &foo()));
    }

    #[test]
    fn a_field_can_choose_its_own_patch_slot() {
        let mut value = foo();
        // `bar` is a counter: it adds, whatever the old value was.
        let changes: patch::Replace<String> = Some("bye".into());
        patch::apply(
            FooShape {
                bar: Counter(2),
                zee: changes,
                nick: None,
            },
            &mut value,
        );
        assert_eq!(value.bar, 7);
        assert_eq!(value.zee, "bye");
    }
}
